from schedule_bot.telegram_utils import reply


def build_faq_text() -> str:
    return (
        "❓ Дайджест команд\n\n"
        "/start — выбрать группу / статус подписки\n"
        "/subscribe, /unsubscribe — включить/выключить рассылку\n"
        "/schedule — расписание на выбранный день\n"
        "/classmates — список одногруппников\n"
        "/change_group — подать заявку на переход в другую группу\n"
        "/starosta — статус старосты, кнопки назначения/смены\n"
        "/votes — открытые голосования группы\n"
        "/requests — заявки на рассмотрении (старосте/админу)\n"
        "/notify — оповестить свою группу (старосте), либо произвольную (админу)\n"
        "/close_group, /open_group — закрыть/открыть группу на вступление\n"
        "/report — сообщить о проблеме администратору\n"
        "/menu — открыть меню с кнопками\n\n"
        "❓ Правила голосования за старосту\n"
        "— нужно 2 «Одобрить» от любых закреплённых за группой участников\n"
        "— «Отклонить» ничего не решает, не блокирует голосование\n"
        "— в группе должно быть минимум 3 участника, иначе голосование не начать\n"
        "— смену старосты можно начинать не чаще раза в 14 дней\n\n"
        "❓ Правила закрытых групп и исключения\n"
        "— в закрытую группу можно вступить только по аппруву старосты или админа\n"
        "— исключённый из группы участник всегда вступает заново только по аппруву, "
        "даже если группа открыта\n"
        "— у одного человека может быть только одна заявка на рассмотрении одновременно"
    )


async def faq_command(update, context) -> None:
    await reply(update, build_faq_text())
